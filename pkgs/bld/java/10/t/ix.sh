{% block patch %}
# libjvm is linked into the launchers: find java.home from the executable
base64 -d << EOF | patch -p1
{% include 'jvm_path.patch/base64' %}
EOF
# NMT placement-news over this "const" static, which clang puts in .rodata
sed -e 's|static const NativeCallStack EMPTY_STACK;|static NativeCallStack EMPTY_STACK;|' \
    -i src/hotspot/share/utilities/nativeCallStack.hpp
sed -e 's|^const NativeCallStack NativeCallStack::EMPTY_STACK|NativeCallStack NativeCallStack::EMPTY_STACK|' \
    -i src/hotspot/share/utilities/nativeCallStack.cpp
# a mark word is an integer carried in a markOopDesc*: clang assumes the
# pointer is 8-aligned and folds every lock-bit test on value() into a
# constant; hide the provenance from it
sed -e 's|uintptr_t value() const { return (uintptr_t) this; }|uintptr_t value() const { uintptr_t v = (uintptr_t) this; __asm__("" : "+r"(v)); return v; }|' \
    -i src/hotspot/share/oops/markOop.hpp
grep -q '__asm__("" : "+r"(v))' src/hotspot/share/oops/markOop.hpp
# clang wants an integer, not a pointer, for the addend of a pointer
sed -e '/PlatformAdd<8>::add_and_fetch/,/^}/ s|return __sync_add_and_fetch(dest, add_value);|return (D)__sync_add_and_fetch((volatile intptr_t*)dest, (intptr_t)add_value);|' \
    -i src/hotspot/os_cpu/linux_zero/atomic_linux_zero.hpp
# clang rejects ordered comparisons of a pointer with 0
sed -e 's|if (p < 0)|if (p == NULL)|' \
    -i src/hotspot/os/linux/os_linux.cpp
# a build JDK needs no GUI: the swing HTML DTD and the AWT icon arrays are
# generated by tools that pull in AWT, leave them empty
sed -e 's|(\$(TOOL_DTDBUILDER) html32 > \$@) \|\| exit 1|$(TOUCH) $@|' \
    -i make/gendata/GendataHtml32dtd.gmk
grep -q 'TOUCH' make/gendata/GendataHtml32dtd.gmk
sed -e 's|\$(CAT) \$\$< \| \$(TOOL_AWT_TOBIN)|$(ECHO)|' \
    -i make/gensrc/GensrcIcons.gmk
# no native java.desktop libraries (awt, fonts, sound, imaging) either:
# they need the real X11 headers
>make/lib/Lib-java.desktop.gmk
# nor the X11 toolkit, whose wrappers are generated against real X11
# headers; nothing outside sun.awt.X11 depends on it
>make/gensrc/GensrcX11Wrappers.gmk
find src/java.desktop/unix/classes/sun/awt/X11 -type f -name '*.java' -delete
# the currency data carries 2015 cut-overs, past the tool's 10-year window
sed -e '/time is more than 10 years from present/d' \
    -i make/jdk/src/classes/build/tools/generatecurrencydata/GenerateCurrencyData.java
# a shifted negative is no integral constant expression for clang
sed -e 's|(-1)<<|((unsigned)(-1)) << |' \
    -i src/jdk.pack/share/native/common-unpack/constants.h
# headless only: X11 is needed for its headers alone, which lib/shim/x11
# provides; there are no X11 libraries to find
sed -e 's|NEEDS_LIB_X11=true|NEEDS_LIB_X11=false|' \
    -i make/autoconf/generated-configure.sh
# a variable defined in a header: one definition per includer without
# -fcommon
sed -e 's|^const char \* const \*parentPathv;|extern const char * const *parentPathv;|' \
    -i src/java.base/unix/native/libjava/childproc.h
echo 'const char * const *parentPathv;' >> src/java.base/unix/native/libjava/childproc.c
# SIGRTMAX is a function call on musl, not a constant initializer
sed -e 's|.*static int sigWakeup.*|#define sigWakeup (__SIGRTMAX - 2)|' \
    -i src/java.base/linux/native/libnet/linux_close.c
