{# The pypy that builds the cffi modules of the real one.

   Those modules are generated by cffi and have to be compiled into the
   interpreter, but generating them needs a working pypy -- so one is
   built first, without them.

   Translated without the JIT on purpose. All this pypy ever does is
   run cffi's code generator: a handful of short processes emitting C
   text, where the JIT never warms up. Measured over the six modules,
   -Ojit ran them in 2.48s against -O2's 2.57s, while translating it
   with the JIT costs 1027s instead of 635s. #}

